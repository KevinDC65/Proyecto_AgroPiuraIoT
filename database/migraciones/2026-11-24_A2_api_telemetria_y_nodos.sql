-- =====================================================================
-- Migración A2 · API de lecturas, token de nodos y estado de conexión
--
-- Añade token_hash y ultima_conexion en dispositivo_iot (base A1), y
-- crea la tabla alerta_nodo para episodios de "nodo sin conexión".
--
-- Idempotente: se puede ejecutar varias veces sin error.
--   psql -h localhost -U postgres -d agropiura -f database/migraciones/2026-11-24_A2_api_telemetria_y_nodos.sql
-- =====================================================================

ALTER TABLE public.dispositivo_iot
    ADD COLUMN IF NOT EXISTS token_hash character varying(255),
    ADD COLUMN IF NOT EXISTS ultima_conexion timestamp without time zone;

CREATE TABLE IF NOT EXISTS public.alerta_nodo (
    id_alerta_nodo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dispositivo integer NOT NULL REFERENCES public.dispositivo_iot(id_dispositivo) ON DELETE CASCADE,
    id_cultivo integer NOT NULL REFERENCES public.cultivo(id_cultivo) ON DELETE CASCADE,
    tipo character varying(40) NOT NULL DEFAULT 'nodo_sin_conexion',
    estado character varying(20) NOT NULL DEFAULT 'abierta',
    severidad character varying(20) NOT NULL DEFAULT 'moderada',
    mensaje character varying(255),
    fecha_alerta timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre timestamp without time zone,
    atendida boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_alerta_nodo_disp_estado
    ON public.alerta_nodo USING btree (id_dispositivo, estado);

CREATE INDEX IF NOT EXISTS idx_alerta_nodo_cultivo_estado
    ON public.alerta_nodo USING btree (id_cultivo, estado);
