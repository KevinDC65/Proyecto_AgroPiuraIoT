-- Migración C1 · Reglas de cuenta y auditoría
--
-- Añade control de intentos fallidos y bloqueo temporal en usuarios,
-- y crea la tabla auditoria para registrar acciones relevantes.
--
-- Idempotente: se puede ejecutar varias veces sin error.
--   psql -h localhost -U postgres -d agropiura -f database/migraciones/2026-11-24_C1_reglas_cuenta_auditoria.sql
-- =====================================================================

ALTER TABLE public.usuarios
    ADD COLUMN IF NOT EXISTS intentos_fallidos integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS bloqueado_hasta timestamp without time zone;

CREATE TABLE IF NOT EXISTS public.auditoria (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
    accion character varying(80) NOT NULL,
    entidad character varying(80) NOT NULL,
    id_entidad integer,
    detalle character varying(500),
    fecha timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_auditoria_fecha
    ON public.auditoria USING btree (fecha DESC);

CREATE INDEX IF NOT EXISTS idx_auditoria_usuario
    ON public.auditoria USING btree (id_usuario);

CREATE INDEX IF NOT EXISTS idx_auditoria_entidad
    ON public.auditoria USING btree (entidad, id_entidad);
